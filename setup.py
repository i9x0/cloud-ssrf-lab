"""Host-side setup for the Cloud SSRF lab (stdlib only).

Generates:
  .env                              random lab credentials (never shown in the report)
  storage/s3-overprivileged.json    identity file: webapp-role may Read/List/Write every bucket
  storage/s3-leastprivilege.json    identity file: webapp-role may only Write to app-uploads
  storage/seed/customers.csv        1,000 SYNTHETIC customer records (no real people)

Run once:  python setup.py
"""
import csv
import json
import random
import secrets
import string
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STORAGE = ROOT / "storage"
SEED = STORAGE / "seed"


def rand_key(prefix: str) -> str:
    alphabet = string.ascii_uppercase + string.digits
    return prefix + "".join(secrets.choice(alphabet) for _ in range(16))


def rand_secret() -> str:
    alphabet = string.ascii_letters + string.digits + "+/"
    return "".join(secrets.choice(alphabet) for _ in range(40))


def load_env() -> dict:
    env_file = ROOT / ".env"
    env = {}
    if env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip()
    return env


def main() -> None:
    env = load_env()
    if not {"ADMIN_KEY", "ADMIN_SECRET", "ROLE_KEY", "ROLE_SECRET"} <= env.keys():
        env = {
            "ADMIN_KEY": rand_key("AKIA"),      # long-term admin key (storage owner)
            "ADMIN_SECRET": rand_secret(),
            "ROLE_KEY": rand_key("ASIA"),       # instance-role key served by the metadata service
            "ROLE_SECRET": rand_secret(),
        }
        (ROOT / ".env").write_text(
            "# Lab-only random credentials generated by setup.py. Do not reuse anywhere.\n"
            + "".join(f"{k}={v}\n" for k, v in env.items()),
            encoding="utf-8",
        )
        print("[+] wrote .env with fresh random lab credentials")
    else:
        print("[=] .env already exists, keeping existing credentials")

    STORAGE.mkdir(exist_ok=True)
    SEED.mkdir(exist_ok=True)

    admin = {
        "name": "admin",
        "credentials": [{"accessKey": env["ADMIN_KEY"], "secretKey": env["ADMIN_SECRET"]}],
        "actions": ["Admin", "Read", "List", "Tagging", "Write"],
    }
    role_creds = [{"accessKey": env["ROLE_KEY"], "secretKey": env["ROLE_SECRET"]}]
    policies = {
        # Capital One-style mistake: the web server's role can read every bucket.
        "overprivileged": ["Read", "List", "Write"],
        # Least privilege: the app only ever needs to upload previews.
        "leastprivilege": ["Write:app-uploads"],
    }
    for name, actions in policies.items():
        doc = {"identities": [admin, {"name": "webapp-role", "credentials": role_creds, "actions": actions}]}
        (STORAGE / f"s3-{name}.json").write_text(json.dumps(doc, indent=2), encoding="utf-8")
        print(f"[+] wrote storage/s3-{name}.json  (webapp-role actions: {actions})")

    # Synthetic customer data: random combinations, fixed seed so results are reproducible.
    rng = random.Random(42)
    first = ["Ahmed", "Sara", "Omar", "Noura", "Khalid", "Reem", "Faisal", "Lama", "Yousef", "Hind",
             "John", "Emily", "David", "Maria", "James", "Linda", "Ali", "Mona", "Saleh", "Dana"]
    last = ["Alharbi", "Alqahtani", "Alshammari", "Alotaibi", "Alanazi", "Smith", "Johnson", "Brown",
            "Garcia", "Miller", "Alzahrani", "Aldosari", "Wilson", "Taylor", "Alghamdi"]
    cities = ["Riyadh", "Jeddah", "Dammam", "Sakaka", "Abha", "Tabuk", "Makkah", "Madinah"]
    rows = []
    for i in range(1, 1001):
        f, l = rng.choice(first), rng.choice(last)
        rows.append({
            "customer_id": f"CUST-{i:05d}",
            "full_name": f"{f} {l}",
            "email": f"{f.lower()}.{l.lower()}{i}@example.com",
            "city": rng.choice(cities),
            "card_last4": f"{rng.randint(0, 9999):04d}",
            "credit_score": rng.randint(300, 850),
            "annual_income_sar": rng.randrange(60000, 900000, 1000),
        })
    with open(SEED / "customers.csv", "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    (SEED / "README-SYNTHETIC.txt").write_text(
        "All records in this bucket are randomly generated for a university lab. No real person is represented.\n",
        encoding="utf-8",
    )
    print(f"[+] wrote storage/seed/customers.csv ({len(rows)} synthetic records)")


if __name__ == "__main__":
    main()
